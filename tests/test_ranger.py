@requires_ranger_lib
@pytest.mark.parametrize(("keys", "fg", "bg", "bold"), CASES, ids=["-".join(c[0]) for c in CASES])
def test_use_mapping(scheme, keys, fg, bg, bold):
    from ranger.gui.color import reverse
    got_fg, got_bg, attr = use(scheme, *keys)
    assert got_fg == (fg if fg == DEFAULT else idx(fg))
    assert got_bg == (bg if bg == DEFAULT else idx(bg))
    assert bool(attr & BOLD()) is bold
    assert not attr & reverse


