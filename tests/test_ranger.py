def tiny_png() -> bytes:
    def chunk(kind: bytes, data: bytes) -> bytes:
        body = kind + data
        return struct.pack(">I", len(data)) + body + struct.pack(">I", zlib.crc32(body))
    header = struct.pack(">IIBBBBB", 1, 1, 8, 0, 0, 0, 0)
    return b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", header) + chunk(b"IDAT", zlib.compress(b"\x00\x00")) + chunk(b"IEND", b"")


def make_tree(root):
    root.mkdir(parents=True)
    (root / "src").mkdir()
    (root / "src" / "main.py").write_text("def main():\n    return 0\n")
    (root / "run.sh").write_text("#!/bin/sh\necho run\n")
    (root / "run.sh").chmod(0o755)
    (root / "app.py").write_text("print('hi')\n")
    (root / "notes.pdf").write_bytes(b"%PDF-1.4\n%%EOF\n")
    (root / "readme.md").write_text("# hi\n")
    (root / "plain.txt").write_text("plain\n")
    (root / "link").symlink_to("app.py")
    (root / "broken").symlink_to("missing")
    os.mkfifo(root / "pipe")
    (root / "bundle.tar.gz").write_bytes(gzip.compress(b"deepwick"))
    (root / "photo.png").write_bytes(tiny_png())
    (root / "clip.mp4").write_bytes(b"\x00\x00\x00\x18ftypmp42")
    return root


def isolated_env(tmp_path, scheme="deepwick", extra=""):
    dirs = {"HOME": tmp_path / "home"}
    for kind in ("CONFIG", "DATA", "STATE", "CACHE"):
        dirs[f"XDG_{kind}_HOME"] = tmp_path / kind.lower()
    for path in dirs.values():
        path.mkdir(parents=True, exist_ok=True)
    conf = dirs["XDG_CONFIG_HOME"] / "ranger"
    (conf / "colorschemes").mkdir(parents=True)
    shutil.copy(SCHEME, conf / "colorschemes" / "deepwick.py")
    (conf / "rc.conf").write_text(
        f"set colorscheme {scheme}\nset draw_borders both\nset preview_files false\nset preview_directories false\n{extra}"
    )
    env = {key: str(path) for key, path in dirs.items()}
    env.update({"TERM": "tmux-256color", "TZ": "UTC"})
    return env


def ranger(tmp_path, tree, scheme="deepwick", extra="", keys=(), after=None, size=(160, 35), wait_for="run.sh"):
    env = isolated_env(tmp_path, scheme, extra)
    return capture(f"cd {tree} && exec {RANGER}", env, size=size, wait_for=wait_for, keys=keys, after=after)


def style_of(out, needle):
    """First run in the file panes (below the title bar) that starts with needle."""
    for chunk, style in runs(out.split("\n", 1)[1]):
        if chunk.strip().startswith(needle):
            return style
    raise AssertionError(f"no run starts with {needle!r}")


def ansi(name):
    return f"ansi256:{idx(name)}"


@requires_ranger
def test_renders_file_types(tmp_path):
    out = ranger(tmp_path, make_tree(tmp_path / "tree"))
    src = style_of(out, "src")
    assert (src["fg"], src["bg"], src["bold"]) == (ansi("blue"), ansi("selection"), True)
    run = style_of(out, "run.sh")
    assert run["fg"] == ansi("green") and run["bold"]
    assert style_of(out, "link")["fg"] == ansi("cyan")
    assert style_of(out, "broken")["fg"] == ansi("red")
    assert style_of(out, "pipe")["fg"] == ansi("gold")
    assert style_of(out, "bundle.tar.gz")["fg"] == ansi("rose")
    assert style_of(out, "photo.png")["fg"] == ansi("magenta")
    assert style_of(out, "clip.mp4")["fg"] == ansi("magenta")
    for name in ("app.py", "notes.pdf", "readme.md", "plain.txt"):
        assert style_of(out, name)["fg"] is None, name
    borders = [style for chunk, style in runs(out) if chunk and set(chunk) <= set("─│┌┐└┘┬┴├┤┼")]
    assert borders and all(style["fg"] == ansi("overlay") for style in borders)


def git(repo, *args):
    env = {**os.environ, "GIT_CONFIG_GLOBAL": "/dev/null", "GIT_AUTHOR_NAME": "Deepwick",
           "GIT_AUTHOR_EMAIL": "deepwick@example.com", "GIT_COMMITTER_NAME": "Deepwick",
           "GIT_COMMITTER_EMAIL": "deepwick@example.com"}
    subprocess.run(["git", "-C", str(repo), *args], env=env, check=True, capture_output=True)


@requires_ranger
def test_renders_marks_and_cut(tmp_path):
    tree = make_tree(tmp_path / "tree")
    # Cut broken first (dd cuts the marked files once any are marked), then mark app.py.
    out = ranger(tmp_path, tree, keys=("j", "j", "d", "d", "k", "Space", "j"))
    marked = style_of(out, "app.py")
    assert marked["fg"] == ansi("yellow") and marked["bold"]
    assert style_of(out, "broken")["fg"] == ansi("muted")


@requires_ranger
def test_renders_vcs(tmp_path):
    tree = make_tree(tmp_path / "tree")
    git(tree, "init", "-q", "-b", "main")
    git(tree, "add", "app.py", "run.sh")
    git(tree, "commit", "-qm", "init")
    (tree / "app.py").write_text("print('changed')\n")
    git(tree, "add", "plain.txt")
    out = ranger(tmp_path, tree, extra="set vcs_aware true\n", wait_for="✓")
    symbols = {chunk.strip(): style["fg"] for chunk, style in runs(out) if chunk.strip() in ("?", "+", "*", "✓")}
    assert symbols == {"?": ansi("teal"), "+": ansi("blue"), "*": ansi("green"), "✓": ansi("green")}


