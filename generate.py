"""Rewrite the generated color block in deepwick.py from Deepwick's 256-color palette.

Run from this directory: PYTHONPATH=../spec python3 generate.py
"""
import re
from pathlib import Path

from deepwick_spec.palette import Palette, load_palette

SCHEME = Path(__file__).with_name("deepwick.py")
BEGIN = "# BEGIN generated by generate.py\n"
END = "# END generated by generate.py\n"
NAMES = ("background", "foreground", "selection", "overlay", "muted", "comment", "blue", "lightBlue", "cyan",
         "teal", "yellow", "gold", "rose", "magenta", "green", "red")


def block(palette: Palette) -> str:
    entries = "".join(f'    "{name}": {palette.xterm256[name]},\n' for name in NAMES)
    return f"{BEGIN}C = {{\n{entries}}}\n{END}"


if __name__ == "__main__":
    text = SCHEME.read_text(encoding="utf-8")
    pattern = re.compile(re.escape(BEGIN) + ".*?" + re.escape(END), re.S)
    SCHEME.write_text(pattern.sub(lambda _: block(load_palette()), text, count=1), encoding="utf-8")
    print(f"wrote {SCHEME.name}")
